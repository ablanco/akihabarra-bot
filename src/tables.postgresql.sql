-- Run against an existing, empty PostgreSQL database as its owner.
BEGIN;

CREATE TABLE users (
    id NUMERIC(20,0) NOT NULL CHECK (id >= 0 AND id <= 18446744073709551615),
    created TIMESTAMPTZ(0) DEFAULT CURRENT_TIMESTAMP,
    modified TIMESTAMPTZ(0) DEFAULT CURRENT_TIMESTAMP,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    username VARCHAR(100) NOT NULL,
    balance NUMERIC(5,2) NOT NULL DEFAULT 0,
    PRIMARY KEY (id)
);

CREATE TABLE articles (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created TIMESTAMPTZ(0) DEFAULT CURRENT_TIMESTAMP,
    modified TIMESTAMPTZ(0) DEFAULT CURRENT_TIMESTAMP,
    name VARCHAR(100) NOT NULL,
    price NUMERIC(5,2) NOT NULL CHECK (price >= 0)
);

CREATE TABLE sales (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created TIMESTAMPTZ(0) DEFAULT CURRENT_TIMESTAMP,
    modified TIMESTAMPTZ(0) DEFAULT CURRENT_TIMESTAMP,
    "user" NUMERIC(20,0) NOT NULL REFERENCES users(id),
    article VARCHAR(100) NOT NULL,
    price NUMERIC(5,2) NOT NULL CHECK (price >= 0)
);

-- Match MariaDB's ON UPDATE behavior, including leaving no-op updates alone.
CREATE FUNCTION update_modified() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF NEW IS DISTINCT FROM OLD AND NEW.modified IS NOT DISTINCT FROM OLD.modified THEN
        NEW.modified = CURRENT_TIMESTAMP;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER users_modified BEFORE UPDATE ON users
    FOR EACH ROW EXECUTE FUNCTION update_modified();
CREATE TRIGGER articles_modified BEFORE UPDATE ON articles
    FOR EACH ROW EXECUTE FUNCTION update_modified();
CREATE TRIGGER sales_modified BEFORE UPDATE ON sales
    FOR EACH ROW EXECUTE FUNCTION update_modified();

COMMIT;
